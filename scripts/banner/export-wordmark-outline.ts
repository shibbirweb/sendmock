#!/usr/bin/env bun
/**
 * Turns the website footer's "SendMock" outline into straight edges for the startup banner
 * (PL-23.6): each quadratic curve becomes short lines, and the points are written to a Rust
 * constant in whole hundredths of a unit, so the binary fills the letters without parsing SVG.
 *
 *     bun scripts/banner/export-wordmark-outline.ts
 */
import { writeFileSync } from "node:fs";

import {
  wordmarkPathData,
  wordmarkViewBoxHeight,
  wordmarkViewBoxWidth,
} from "../../website/components/footer-wordmark/sendmock-wordmark-path";

export const outlineRustFilePath = "crates/sendmock/src/startup_banner/wordmark_outline.rs";

/** Enough lines per curve that a 12-line banner shows no corners on the round letters. */
const segmentsPerCurve = 6;
const hundredthsPerUnit = 100;

type Point = [number, number];

function readNumbers(tokens: string[], startIndex: number, count: number): number[] {
  return tokens.slice(startIndex, startIndex + count).map(Number);
}

function pointOnCurve(start: Point, control: Point, end: Point, position: number): Point {
  const remaining = 1 - position;
  return [
    remaining * remaining * start[0] + 2 * remaining * position * control[0] + position * position * end[0],
    remaining * remaining * start[1] + 2 * remaining * position * control[1] + position * position * end[1],
  ];
}

/** The closed shapes of a path made of absolute M, L, Q and Z commands, curves flattened. */
export function flattenWordmarkPath(pathData: string): Point[][] {
  const tokens = pathData.match(/[MLQZ]|-?\d*\.?\d+/g) ?? [];
  const contours: Point[][] = [];
  let currentContour: Point[] = [];
  let tokenIndex = 0;
  while (tokenIndex < tokens.length) {
    const command = tokens[tokenIndex];
    tokenIndex += 1;
    if (command === "M") {
      currentContour = [readNumbers(tokens, tokenIndex, 2) as Point];
      contours.push(currentContour);
      tokenIndex += 2;
    } else if (command === "L") {
      currentContour.push(readNumbers(tokens, tokenIndex, 2) as Point);
      tokenIndex += 2;
    } else if (command === "Q") {
      const [controlX, controlY, endX, endY] = readNumbers(tokens, tokenIndex, 4);
      const start = currentContour[currentContour.length - 1] ?? [0, 0];
      for (let segment = 1; segment <= segmentsPerCurve; segment += 1) {
        currentContour.push(
          pointOnCurve(start, [controlX ?? 0, controlY ?? 0], [endX ?? 0, endY ?? 0], segment / segmentsPerCurve),
        );
      }
      tokenIndex += 4;
    } else if (command !== "Z") {
      throw new Error(`The wordmark path uses ${command}; only absolute M, L, Q and Z are read.`);
    }
  }
  return contours;
}

function toHundredths(value: number): number {
  return Math.round(value * hundredthsPerUnit);
}

/** The Rust source of `wordmark_outline.rs`, compared with the committed file by a test. */
export function renderOutlineRustSource(contours: Point[][]): string {
  const contourLines = contours.map((contour) => {
    const points = contour.map(([x, y]) => `[${toHundredths(x)}, ${toHundredths(y)}]`);
    return `    &[${points.join(", ")}],`;
  });
  return [
    "//! Generated by `bun scripts/banner/export-wordmark-outline.ts` from",
    "//! `website/components/footer-wordmark/sendmock-wordmark-path.ts`; do not edit by hand.",
    "//! \"SendMock\" in Oswald Regular (SIL Open Font License), as closed shapes of straight edges.",
    "",
    "/// The drawing area, in hundredths of a unit.",
    `pub const VIEW_BOX_WIDTH_HUNDREDTHS: u16 = ${toHundredths(wordmarkViewBoxWidth)};`,
    `pub const VIEW_BOX_HEIGHT_HUNDREDTHS: u16 = ${toHundredths(wordmarkViewBoxHeight)};`,
    "",
    "/// Each letter's outlines and holes as points `[x, y]` in hundredths of a unit, y down.",
    "#[rustfmt::skip]",
    "pub const WORDMARK_CONTOURS: &[&[[u16; 2]]] = &[",
    ...contourLines,
    "];",
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(outlineRustFilePath, renderOutlineRustSource(flattenWordmarkPath(wordmarkPathData)));
  console.log(`Wrote ${outlineRustFilePath}.`);
}
