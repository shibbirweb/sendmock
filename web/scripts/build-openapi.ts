/**
 * Builds docs/api/openapi.yaml from the endpoint registry and the TypeScript
 * API types (UI-09). `bun run openapi` writes it; `--check` fails when the
 * committed file differs from a fresh build.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { stringify } from "yaml";

import { apiEndpoints } from "../src/lib/api/endpoint-registry";
import { buildOpenApiDocument } from "./openapi/build-document";
import { generateComponentSchemas } from "./openapi/generate-schemas";

const webDirectory = join(import.meta.dir, "..");
export const openApiFilePath = join(webDirectory, "../docs/api/openapi.yaml");

const fileHeader = [
  "# Generated by `bun run openapi` (web/scripts/build-openapi.ts) from",
  "# web/src/lib/api/endpoint-registry and web/src/lib/api/types.",
  "# Do not edit by hand; change the registry or the types and run it again.",
  "",
].join("\n");

export function renderOpenApiYaml(): string {
  const openApiDocument = buildOpenApiDocument(
    apiEndpoints,
    generateComponentSchemas(apiEndpoints, webDirectory),
  );

  return fileHeader + stringify(openApiDocument, { lineWidth: 0 });
}

if (import.meta.main) {
  const freshYaml = renderOpenApiYaml();
  if (process.argv.includes("--check")) {
    const committedYaml = readFileSync(openApiFilePath, "utf8");
    if (committedYaml !== freshYaml) {
      console.error(
        "docs/api/openapi.yaml is out of date. Run `bun run openapi` in web/ and commit it.",
      );
      process.exit(1);
    }
    console.log("docs/api/openapi.yaml is up to date.");
  } else {
    writeFileSync(openApiFilePath, freshYaml);
    console.log(
      `Wrote docs/api/openapi.yaml (${apiEndpoints.length} endpoints).`,
    );
  }
}
