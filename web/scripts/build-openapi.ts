/**
 * Builds docs/api/openapi.yaml from the endpoint registry and the TypeScript
 * API types (UI-09), and the CLI and MCP references derived from it,
 * docs/api/cli-reference.json and docs/api/mcp-tools.json (WS-07.5).
 * `bun run openapi` writes them; `--check` fails when a committed file
 * differs from a fresh build.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { stringify } from "yaml";

import { apiEndpoints } from "../src/lib/api/endpoint-registry";
import { buildOpenApiDocument } from "./openapi/build-document";
import { generateComponentSchemas } from "./openapi/generate-schemas";
import { renderSurfaceReferences } from "./surfaces/reference/render-surface-references";
import type { SpecDocument } from "./surfaces/reference/spec-reader";

const webDirectory = join(import.meta.dir, "..");
const apiDocsDirectory = join(webDirectory, "../docs/api");
export const openApiFilePath = join(apiDocsDirectory, "openapi.yaml");
export const cliReferenceFilePath = join(
  apiDocsDirectory,
  "cli-reference.json",
);
export const mcpToolsFilePath = join(apiDocsDirectory, "mcp-tools.json");

const fileHeader = [
  "# Generated by `bun run openapi` (web/scripts/build-openapi.ts) from",
  "# web/src/lib/api/endpoint-registry and web/src/lib/api/types.",
  "# Do not edit by hand; change the registry or the types and run it again.",
  "",
].join("\n");

function buildSpecDocument() {
  return buildOpenApiDocument(
    apiEndpoints,
    generateComponentSchemas(apiEndpoints, webDirectory),
  );
}

export function renderOpenApiYaml(): string {
  return fileHeader + stringify(buildSpecDocument(), { lineWidth: 0 });
}

/** The spec and both references, by file path, and any rule breaks. */
export function renderApiFiles() {
  const specDocument = buildSpecDocument();
  const surfaceReferences = renderSurfaceReferences(
    specDocument as unknown as SpecDocument,
  );

  return {
    renderedFiles: new Map([
      [openApiFilePath, fileHeader + stringify(specDocument, { lineWidth: 0 })],
      [cliReferenceFilePath, surfaceReferences.cliReferenceJson],
      [mcpToolsFilePath, surfaceReferences.mcpToolsJson],
    ]),
    problems: surfaceReferences.problems,
  };
}

function readCommittedFile(filePath: string): string {
  try {
    return readFileSync(filePath, "utf8");
  } catch {
    return "";
  }
}

if (import.meta.main) {
  const { renderedFiles, problems } = renderApiFiles();
  if (problems.length > 0) {
    console.error(
      `The CLI and MCP rules found ${problems.length} problems:\n- ${problems.join("\n- ")}`,
    );
    process.exit(1);
  }
  const fileNames = [...renderedFiles.keys()].map((filePath) =>
    filePath.replace(`${apiDocsDirectory}/`, "docs/api/"),
  );
  if (process.argv.includes("--check")) {
    const staleFiles = [...renderedFiles].filter(
      ([filePath, freshText]) => readCommittedFile(filePath) !== freshText,
    );
    if (staleFiles.length > 0) {
      console.error(
        `${staleFiles.map(([filePath]) => filePath.replace(`${apiDocsDirectory}/`, "docs/api/")).join(", ")} out of date. Run \`bun run openapi\` in web/ and commit.`,
      );
      process.exit(1);
    }
    console.log(`${fileNames.join(", ")} are up to date.`);
  } else {
    for (const [filePath, freshText] of renderedFiles) {
      writeFileSync(filePath, freshText);
    }
    console.log(
      `Wrote ${fileNames.join(", ")} (${apiEndpoints.length} endpoints).`,
    );
  }
}
